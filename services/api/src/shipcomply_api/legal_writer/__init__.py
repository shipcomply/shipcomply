def _derive_citations_for_section(title: str, element_types: list[str], scan) -> list[str]:
    """Map section title to relevant PII types and collect their source citations."""
    relevant_types: dict[str, list[str]] = {
        "What Data We Collect": element_types,
        "Legal Basis for Processing": element_types,
        "Children's Data": ["dob"],
        "Your Rights": element_types,
        "Security Measures": element_types,
        "Data Retention": element_types,
        "Special Category Data": ["dob", "pan", "aadhaar", "ssn", "payment"],
        "Right to Know": element_types,
        "Right to Delete": element_types,
        "Right to Opt-Out": ["analytics", "email"],
        "Non-Discrimination": [],
        "Contact Us": [],
    }
    target_types = relevant_types.get(title, [])
    citations = []
    for el in scan.data_elements:
        if el.element_type in target_types:
            for src in el.sources:
                cite = f"{src.file}:{src.line}"
                if cite not in citations:
                    citations.append(cite)
    return citations[:8]


def _fetch_rag_scores(rag, query: str, jurisdiction: str) -> list[float]:
    if rag is None:
        return []
    try:
        chunks = rag.retrieve(query, jurisdiction=jurisdiction, top_k=3)
        return [getattr(c, "score", 0.0) for c in chunks]
    except Exception:
        return []


def _llm_section(llm, title: str, element_types: list[str], citations: list[str], jurisdiction: str) -> str:
    pii_list = ", ".join(PII_FRIENDLY.get(t, t) for t in element_types)
    cite_str = "\n".join(f"  - {c}" for c in citations) if citations else "  (no specific citations)"
    prompt = (
        f"Write the '{title}' section of a privacy policy for a web application.\n"
        f"Jurisdiction: {jurisdiction}\n"
        f"Detected PII types: {pii_list}\n"
        f"Code references:\n{cite_str}\n\n"
        "Requirements:\n"
        "- 2-4 sentences, plain English, legally accurate for the jurisdiction\n"
        "- Reference the specific PII types found\n"
        "- Do not include section headers\n"
        "- Return only the section body text"
    )
    import asyncio, concurrent.futures
    # run_until_complete inside a running FastAPI loop raises RuntimeError;
    # use a thread executor so the coroutine runs in its own loop instead.
    def _run() -> str:
        return asyncio.run(
            llm.complete(task="SHORT_GEN", system="You are a privacy policy legal writer.", user=prompt)
        )
    with concurrent.futures.ThreadPoolExecutor(max_workers=1) as pool:
        future = pool.submit(_run)
        return future.result(timeout=30).strip()

