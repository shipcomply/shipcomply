@dataclass
class CitedSection:
    title: str
    regulation_ref: str
    body: str
    citations: list[str]          # ["app/page.tsx:12", "lib/actions.ts:5"]
    confidence: int               # 0-100
    jurisdiction: str


@dataclass
class GeneratedPolicy:
    scan_id: str
    jurisdiction: str
    sections: list[CitedSection] = field(default_factory=list)
    generated_at: str = field(default_factory=lambda: datetime.now(timezone.utc).isoformat())

    def to_markdown(self) -> str:
        lines = [
            f"<!--\n{DISCLAIMER}-->",
            f"<!-- shipcomply-managed: {self.scan_id} -->",
            "",
            "# Privacy Policy",
            "",
            f"*Last updated: {self.generated_at[:10]}*",
            "",
            "> **AI-GENERATED DRAFT — REVIEW BY QUALIFIED ATTORNEY BEFORE PUBLISHING**",
            "",
        ]
        for section in self.sections:
            conf_label = _confidence_label(section.confidence)
            lines += [
                f"## {section.title}",
                "",
                f"*Regulation: {section.regulation_ref} · Confidence: {conf_label} ({section.confidence}%)*",
                "",
                section.body,
                "",
            ]
            if section.citations:
                lines.append("**Detected in codebase:**")
                for cite in section.citations:
                    lines.append(f"- `{cite}`")
                lines.append("")
        return "\n".join(lines)

    def to_dict(self) -> dict:
        return {
            "scan_id": self.scan_id,
            "jurisdiction": self.jurisdiction,
            "generated_at": self.generated_at,
            "sections": [
                {
                    "title": s.title,
                    "regulation_ref": s.regulation_ref,
                    "body": s.body,
                    "citations": s.citations,
                    "confidence": s.confidence,
                    "jurisdiction": s.jurisdiction,
                }
                for s in self.sections
            ],
        }


def _confidence_label(score: int) -> str:
    if score >= 80:
        return "High"
    if score >= 50:
        return "Medium"
    return "Low"


def _collect_citations(element_type: str, scan) -> list[str]:
    """Return file:line strings for all sources of a given element type."""
    citations = []
    for el in scan.data_elements:
        if el.element_type == element_type:
            for src in el.sources:
                citations.append(f"{src.file}:{src.line}")
    return citations[:10]  # cap to avoid overwhelming the policy


def _confidence_from_citations(citations: list[str], chunk_scores: list[float]) -> int:
    cite_score = min(len(citations) * 15, 60)   # up to 60 pts from citations
    rag_score = int(max(chunk_scores or [0]) * 40)  # up to 40 pts from RAG rank
    return min(cite_score + rag_score, 100)


class PolicyGenerator:
    """
    Generates a PRIVACY.md given a ScanResult.
    Uses LLM for body text if available; falls back to template expansion.
    """

    def __init__(self, llm_client=None, rag_retriever=None):
        self._llm = llm_client
        self._rag = rag_retriever

    def generate(self, scan, jurisdiction: str = "DPDP") -> GeneratedPolicy:
        from shipcomply_api.scanner import ScanResult  # avoid circular at module level

        element_types = list({el.element_type for el in scan.data_elements})
        sections_config = SECTION_MAP.get(jurisdiction, SECTION_MAP["DPDP"])

        policy = GeneratedPolicy(scan_id=scan.scan_id, jurisdiction=jurisdiction)

        for title, reg_ref in sections_config.items():
            citations = _derive_citations_for_section(title, element_types, scan)
            chunk_scores = _fetch_rag_scores(self._rag, title, jurisdiction)
            confidence = _confidence_from_citations(citations, chunk_scores)

            body = self._generate_section_body(title, element_types, citations, jurisdiction)
            policy.sections.append(
                CitedSection(
                    title=title,
                    regulation_ref=reg_ref,
                    body=body,
                    citations=citations,
                    confidence=confidence,
                    jurisdiction=jurisdiction,
                )
            )

        log.info(
            "policy generated scan_id=%s jurisdiction=%s sections=%d",
            scan.scan_id,
            jurisdiction,
            len(policy.sections),
        )
        return policy

    def _generate_section_body(
        self,
        title: str,
        element_types: list[str],
        citations: list[str],
        jurisdiction: str,
    ) -> str:
        if self._llm is not None:
            try:
                return _llm_section(self._llm, title, element_types, citations, jurisdiction)
            except Exception as exc:
                log.warning("LLM section generation failed, using template: %s", exc)
        return _template_section(title, element_types, jurisdiction)


