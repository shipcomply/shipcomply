class CodeGenerator:
    """Generates working TS/React artifacts from a ScanResult."""

    def generate(self, scan, target_path: Optional[str] = None) -> CodeGenResult:
        pii_types = list({el.element_type for el in scan.data_elements})
        result = CodeGenResult(scan_id=scan.scan_id)

        artifacts = [
            GeneratedFile(
                filename="ConsentBanner.tsx",
                path="components/ConsentBanner.tsx",
                content=_consent_banner_tsx(scan.scan_id, pii_types),
                scan_id=scan.scan_id,
            ),
            GeneratedFile(
                filename="consent.ts",
                path="app/api/consent/route.ts",
                content=_consent_api_route(scan.scan_id),
                scan_id=scan.scan_id,
            ),
            GeneratedFile(
                filename="user-data.ts",
                path="app/api/user/data/route.ts",
                content=_user_data_api_route(scan.scan_id, pii_types),
                scan_id=scan.scan_id,
            ),
        ]

        for artifact in artifacts:
            if target_path:
                full = os.path.join(target_path, artifact.path)
                if os.path.exists(full):
                    artifact.collision = True
                    # Rename to avoid overwrite: components/shipcomply-ConsentBanner.tsx
                    parts = artifact.path.rsplit("/", 1)
                    artifact.path = f"{parts[0]}/shipcomply-{parts[1]}" if len(parts) > 1 else f"shipcomply-{artifact.path}"
                    log.warning("collision: %s -> %s", artifact.filename, artifact.path)
            result.files.append(artifact)

        log.info("code_gen scan_id=%s files=%d", scan.scan_id, len(result.files))
        return result

    def write_to_disk(self, result: CodeGenResult, target_path: str) -> list[str]:
        """Write all generated files to disk. Returns list of written paths."""
        written = []
        for f in result.files:
            full = os.path.join(target_path, f.path)
            os.makedirs(os.path.dirname(full), exist_ok=True)
            with open(full, "w", encoding="utf-8") as fp:
                fp.write(f.content)
            written.append(full)
            log.info("wrote %s", full)
        return written
