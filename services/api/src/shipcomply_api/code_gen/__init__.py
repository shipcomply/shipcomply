"""
Code Generator — produces working TypeScript/React artifacts from a ScanResult.

Artifacts:
  1. ConsentBanner.tsx   — React consent banner (accept/reject, persists to localStorage + API)
  2. api/consent.ts      — Next.js API route to store/retrieve consent decisions
  3. api/user-data.ts    — Next.js API route for DPDP/GDPR data export + deletion

Every generated file:
  - Carries "// shipcomply-managed: <scan_id>" header (idempotent regen marker)
  - Is prefixed with the AI-GENERATED DRAFT disclaimer
  - Has collision detection: if the target path already exists, renames to shipcomply-<name>
"""
from __future__ import annotations

import logging
import os
from dataclasses import dataclass, field
from pathlib import Path
from typing import Optional

log = logging.getLogger(__name__)

DISCLAIMER_COMMENT = """\
// AI-GENERATED DRAFT — REVIEW BY QUALIFIED ATTORNEY BEFORE PUBLISHING
// Generated by ShipComply (https://shipcomply.dev)
"""


@dataclass
class GeneratedFile:
    filename: str           # e.g. "ConsentBanner.tsx"
    path: str               # relative path in the target repo
    content: str
    scan_id: str
    collision: bool = False # True if target path already existed


@dataclass
class CodeGenResult:
    scan_id: str
    files: list[GeneratedFile] = field(default_factory=list)

    def to_dict(self) -> dict:
        return {
            "scan_id": self.scan_id,
            "files": [
                {
                    "filename": f.filename,
                    "path": f.path,
                    "collision": f.collision,
                    "content_length": len(f.content),
                }
                for f in self.files
            ],
        }


